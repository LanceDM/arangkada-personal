/**
 * The group's question bank (arangkada-question-bank.xlsx, 355 items), one
 * shared bank for the short quizzes, the 55-item diagnostic (5 per
 * competency) and the 60-item post-evaluation exam.
 *
 * Every item is tagged with one competency and the module (stage) that teaches
 * it, and cites its source. The competency tags are the group's; two taggers
 * still review them (Cohen's kappa) before the study.
 */
import type { DrivingCompetency } from '@/domain/learner/competency';
import bank from './questionBank.json';
import blueprint from './assessmentBlueprint.json';

export interface BankItem {
  /** Module-Competency-Number, e.g. L1-DL-01. */
  id: string;
  question: string;
  /** Under the app's public folder; absent for a text-only item. */
  image?: string;
  /** Four choices, A to D. */
  choices: string[];
  /** Index of the correct choice. */
  answer: number;
  competency: DrivingCompetency;
  /** The module that teaches it: 1-11. */
  stage: number;
  source: string;
  reviewerNotes?: string;
}

export const QUESTION_BANK: readonly BankItem[] = bank as BankItem[];

const byId = new Map(QUESTION_BANK.map(item => [item.id, item]));

export const bankItem = (id: string): BankItem | undefined => byId.get(id);

/**
 * TENTATIVE: which items make the diagnostic pre-test and the post-evaluation
 * exam, per competency. Generated by spreading each competency's items over its
 * stages; the group and the LTO reviewers confirm or replace these lists.
 */
export const DIAGNOSTIC_ITEMS: Readonly<Record<DrivingCompetency, readonly string[]>> =
  blueprint.diagnostic as Record<DrivingCompetency, string[]>;
export const POST_EXAM_ITEMS: Readonly<Record<DrivingCompetency, readonly string[]>> =
  blueprint.postExam as Record<DrivingCompetency, string[]>;

/** Post-exam items are kept out of the short quizzes, so the exam is unseen when it is sat. */
export const RESERVED_FOR_POST_EXAM: ReadonlySet<string> = new Set(Object.values(POST_EXAM_ITEMS).flat());

export const itemsFor = (ids: readonly string[]): BankItem[] =>
  ids.map(id => {
    const item = byId.get(id);
    if (!item) throw new Error(`question bank has no item ${id}`);
    return item;
  });
