/**
 * A fresh roll of the drive: one checkpoint scenario from each slot's pool.
 * This level has no sign/marking catalogue for coverage tracking (its content
 * is legal-document checkpoints, not signs), so `coverage` is accepted only
 * for signature parity with the other pool-based levels and is unused here.
 * A weakCompetency narrows each slot's pool to variants tagged with that
 * competency first - a no-op for slots that are entirely one competency.
 */
